/**
 * КОПІЮВАННЯ І ВСТАВКА ОБ'ЄКТІВ — Cmd+C / Cmd+V. Переносний модуль, нуль залежностей.
 *
 * Текст браузер копіює сам, і чіпати це не можна. Тут — про інше: скопіювати крок
 * процесу, запис, рядок сітки, картку. Тобто об'єкт, а не рядок символів.
 *
 * Формат навмисно подвійний:
 *   - у системний буфер лягає ЛЮДСЬКИЙ текст, щоб вставка в чат чи пошту дала
 *     щось читабельне, а не купу дужок;
 *   - сам об'єкт їде причепленим до тексту окремим рядком-міткою, який людина
 *     не бачить у більшості полів, зате наш обробник упізнає.
 *
 * Чому не тільки внутрішня змінна: між двома вкладками одного сервісу теж треба
 * копіювати, а спільної пам'яті в них немає. Системний буфер — єдиний спільний.
 * Внутрішня копія лишається запасним шляхом: коли браузер не дав доступу до буфера
 * (немає дозволу, не той контекст), Cmd+V у межах вкладки все одно спрацює.
 */
"use client";

const МІТКА = "nlo-clip:";

export type Ноша = {
  /** Що це: "process-step", "record", "row" — упізнає той екран, який вставляє. */
  вид: string;
  /** Звідки скопійовано: щоб не вставити крок процесу в фінансовий звіт. */
  звідки?: string;
  /** Самі дані. */
  дані: unknown;
  /** Людський опис — його ж людина побачить, якщо вставить у звичайне поле. */
  підпис: string;
};

let внутрішня: Ноша | null = null;

function запакувати(н: Ноша): string {
  return `${н.підпис}\n${МІТКА}${JSON.stringify({ вид: н.вид, звідки: н.звідки, дані: н.дані })}`;
}

function розпакувати(текст: string): Ноша | null {
  const i = текст.indexOf(МІТКА);
  if (i < 0) return null;
  try {
    const o = JSON.parse(текст.slice(i + МІТКА.length)) as Omit<Ноша, "підпис">;
    if (!o || typeof o.вид !== "string") return null;
    return { ...o, підпис: текст.slice(0, i).trim() };
  } catch {
    return null;
  }
}

/** Покласти об'єкт у буфер. Повертає false, якщо системний буфер недоступний. */
export async function копіювати(н: Ноша): Promise<boolean> {
  внутрішня = н;
  try {
    await navigator.clipboard.writeText(запакувати(н));
    return true;
  } catch {
    return false;   // лишаємось на внутрішній копії — у межах вкладки працює
  }
}

/**
 * Дістати об'єкт із буфера.
 * `подія` — той самий ClipboardEvent, якщо вставка прийшла з Cmd+V: у ньому дані
 * доступні без дозволу на читання буфера, і це найнадійніший шлях.
 */
export async function вставити(подія?: ClipboardEvent): Promise<Ноша | null> {
  const зПодії = подія?.clipboardData?.getData("text/plain");
  if (зПодії) {
    const н = розпакувати(зПодії);
    if (н) return н;
    // У буфері звичайний текст — не наш об'єкт. Це не помилка: людина щось скопіювала
    // деінде. Але якщо своя копія свіжіша, беремо її.
    return внутрішня;
  }
  try {
    const текст = await navigator.clipboard.readText();
    return розпакувати(текст) ?? внутрішня;
  } catch {
    return внутрішня;
  }
}

/** Що зараз у власній копії — щоб екран міг підсвітити «є що вставити». */
export function ушеБуфері(): Ноша | null {
  return внутрішня;
}
