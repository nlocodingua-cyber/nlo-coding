/**
 * ІСТОРІЯ ДІЙ — переносний модуль. Нуль залежностей, тільки React.
 *
 * Навіщо клієнтська історія, коли на сервері вже є журнал змін: журнал знає тільки
 * те, що доїхало до бази, і навмисно не пише дрібницю на кшталт координат вузла —
 * інакше стрічка простору тоне в сотнях подій, поки людина возить мишею. А відкотити
 * перетягування хочеться саме одразу. Тому працюють обидва рівні:
 *
 *   клієнтський стек — усе, що людина зробила В ЦІЙ вкладці, включно з дрібницею
 *   серверний журнал — глибша пам'ять; коли стек порожній, крок бере звідти
 *
 * Екран реєструє дію одним викликом `запамʼятати({ опис, вперед, назад })`. Обидві
 * функції мають бути самодостатні: історія кличе їх коли завгодно і скільки завгодно.
 *
 * Правило, яке легко порушити: `вперед` НЕ виконується під час запису. Дію людина вже
 * зробила; повторний виклик подвоїв би її. Запис лише запам'ятовує, як повторити.
 */
"use client";

import { useSyncExternalStore } from "react";

export type Крок = {
  /** Людською мовою, для тоста: «Пересунуто крок», «Змінено стрілку». */
  опис: string;
  /** Виконати дію (повтор після скасування). */
  вперед: () => void | Promise<void>;
  /** Відкотити дію. */
  назад: () => void | Promise<void>;
  /**
   * Ключ злиття. Тридцять кадрів перетягування — це один крок історії, а не
   * тридцять. Однаковий ключ підряд → кроки зливаються в один.
   */
  злити?: string;
};

/** Глибина: далі людина все одно не пам'ятає, а тримати важче. */
const МЕЖА = 60;

type Стан = { назад: Крок[]; вперед: Крок[] };

let стан: Стан = { назад: [], вперед: [] };
let зайнято = false;
const слухачі = new Set<() => void>();

function оновити(next: Стан) {
  стан = next;
  for (const s of слухачі) s();
}

function підписка(fn: () => void) {
  слухачі.add(fn);
  return () => { слухачі.delete(fn); };
}

/** Записати виконану дію в історію. */
export function запамʼятати(крок: Крок): void {
  const назад = стан.назад.slice();
  const останній = назад[назад.length - 1];
  // Злиття: беремо `назад` найпершого кроку серії (щоб відкат вернув у початкову
  // точку) і `вперед` найсвіжішого (щоб повтор привів у кінцеву).
  if (крок.злити && останній?.злити === крок.злити) {
    назад[назад.length - 1] = { ...крок, назад: останній.назад };
  } else {
    назад.push(крок);
    if (назад.length > МЕЖА) назад.shift();
  }
  // Нова дія обриває гілку «вперед» — повтор вів би у світ, якого вже немає.
  оновити({ назад, вперед: [] });
}

/** Крок назад. Повертає опис зробленого або null, якщо історія порожня. */
export async function скасувати(): Promise<string | null> {
  if (зайнято) return null;
  const крок = стан.назад[стан.назад.length - 1];
  if (!крок) return null;
  зайнято = true;
  try {
    await крок.назад();
    оновити({ назад: стан.назад.slice(0, -1), вперед: [...стан.вперед, крок] });
    return крок.опис;
  } finally {
    зайнято = false;
  }
}

/** Крок уперед. Повертає опис або null. */
export async function повторити(): Promise<string | null> {
  if (зайнято) return null;
  const крок = стан.вперед[стан.вперед.length - 1];
  if (!крок) return null;
  зайнято = true;
  try {
    await крок.вперед();
    оновити({ вперед: стан.вперед.slice(0, -1), назад: [...стан.назад, крок] });
    return крок.опис;
  } finally {
    зайнято = false;
  }
}

/** Перехід на інший екран: чужі кроки відкочувати нікуди. */
export function очиститиІсторію(): void {
  оновити({ назад: [], вперед: [] });
}

export function є(): { назад: boolean; вперед: boolean } {
  return { назад: стан.назад.length > 0, вперед: стан.вперед.length > 0 };
}

const ПУСТО: Стан = { назад: [], вперед: [] };

/** Для кнопок «скасувати/повернути», якщо треба показати їх в інтерфейсі. */
export function useHistory(): { можнаНазад: boolean; можнаВперед: boolean } {
  const s = useSyncExternalStore(підписка, () => стан, () => ПУСТО);
  return { можнаНазад: s.назад.length > 0, можнаВперед: s.вперед.length > 0 };
}
